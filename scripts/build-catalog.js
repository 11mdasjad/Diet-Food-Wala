import {readFile, writeFile} from 'node:fs/promises';
const catalog = JSON.parse(await readFile('data/catalog-source.json', 'utf8'));
const ids = new Set();
for (const product of catalog.products) {
  if (ids.has(product.id) || !product.name || !Number.isFinite(product.price) || product.price <= 0) throw new Error(`Invalid catalog item: ${product.id}`);
  ids.add(product.id);
  for (const variant of product.variants || []) if (!Number.isFinite(variant.price) || variant.price <= 0) throw new Error(`Invalid variant: ${product.id}`);
}
await writeFile('js/catalog-data.js', '// Generated by scripts/build-catalog.js from data/catalog-source.json.\nexport default ' + JSON.stringify(catalog.products, null, 2) + ';\n');
console.log(`Prepared ${ids.size} catalog products.`);
